def load_rows(path):
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def aggregate(rows):
    """data[(scenario, policy)][metric] = list of per-seed values (nan dropped)."""
    data = defaultdict(lambda: defaultdict(list))
    for r in rows:
        for m in METRICS:
            try:
                v = float(r[m])
            except (KeyError, ValueError):
                continue
            if not math.isnan(v):
                data[(r["scenario"], r["policy"])][m].append(v)
    return data


def mean(data, sc, pol, metric):
    xs = data[(sc, pol)].get(metric, [])
    return float(np.mean(xs)) if xs else float("nan")


def std(data, sc, pol, metric):
    xs = data[(sc, pol)].get(metric, [])
    return float(np.std(xs, ddof=1)) if len(xs) > 1 else 0.0


def fmt(x, d=2):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    return "{:.{}f}".format(x, d)


def pm(data, sc, pol, metric, d=2):
    m = mean(data, sc, pol, metric)
    if math.isnan(m):
        return "--"
    return "{}\\,$\\pm$\\,{}".format(fmt(m, d), fmt(std(data, sc, pol, metric), d))


def best(data, sc, metric, lower, exclude_oracle=True):
    vals = {}
    for pol in POLICIES:
        if exclude_oracle and pol == "oracle":
            continue
        v = mean(data, sc, pol, metric)
        if not math.isnan(v):
            vals[pol] = v
    if not vals:
        return None
    return (min if lower else max)(vals, key=vals.get)


