def holm(pvals):
    idx = sorted(range(len(pvals)), key=lambda i: pvals[i])
    adj, run = [0.0] * len(pvals), 0.0
    for rank, i in enumerate(idx):
        run = max(run, min(1.0, (len(pvals) - rank) * pvals[i]))
        adj[i] = run
    return adj


def stats_table(data):
    """Paired tests of Full vs four baselines, aggregated per seed over attack scenarios."""
    baselines = ["static_high", "threshold", "risk_only", "static_low"]
    metrics = [("utility", False), ("unsafe_grant", True), ("ivr_per_1k", True)]
    with open(MAIN, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    per = defaultdict(lambda: defaultdict(list))  # (policy, metric) -> {seed: [vals]}
    for r in rows:
        if r["scenario"] not in ATTACK:
            continue
        for key, _ in metrics:
            try:
                v = float(r[key])
            except ValueError:
                continue
            if not math.isnan(v):
                per[(r["policy"], key)][r["run"]].append(v)

    def seed_mean(pol, key):
        return {s: float(np.mean(v)) for s, v in per[(pol, key)].items()}

    lines = [
        "% Generated by make_paper_assets.py. Paired by seed; values are means over the",
        "% seven attack scenarios per seed (n=10). Wilcoxon signed-rank, Holm within metric.",
        r"\begin{table}[t]", r"\centering", r"\small",
        r"\caption{Paired comparison against Full, aggregated over the seven attack scenarios",
        r"per seed ($n=10$). $\Delta$ is Full minus baseline; a negative $\Delta$ for",
        r"malicious grant and IVR is better. $p_{\text{Holm}}$ is within the metric across",
        r"the four baselines. Em dashes mark identical vectors (no test).}",
        r"\label{tab:stats}",
        r"\begin{tabular}{lcccccc}",
        r"\toprule",
        r" & \multicolumn{2}{c}{Utility $\uparrow$} & \multicolumn{2}{c}{Malicious grant $\downarrow$} & \multicolumn{2}{c}{IVR/1k $\downarrow$} \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
        r"Baseline & $\Delta$ & $p_{\text{Holm}}$ & $\Delta$ & $p_{\text{Holm}}$ & $\Delta$ & $p_{\text{Holm}}$ \\",
        r"\midrule",
    ]
    full = {key: seed_mean("full", key) for key, _ in metrics}
    raw = {key: [] for key, _ in metrics}
    rows_out = {}
    for b in baselines:
        rows_out[b] = {}
        for key, _ in metrics:
            bvals = seed_mean(b, key)
            common = sorted(set(full[key]) & set(bvals))
            d = np.array([full[key][s] - bvals[s] for s in common])
            delta = float(d.mean())
            if np.allclose(d, 0.0):
                p = None
            elif len(common) >= 6:
                try:
                    p = float(sps.wilcoxon(d, zero_method="wilcox").pvalue)
                except ValueError:
                    p = None
            else:
                p = None
            rows_out[b][key] = (delta, p)
            if p is not None:
                raw[key].append((b, p))
    adj = {key: dict(zip([b for b, _ in raw[key]], holm([p for _, p in raw[key]])))
           for key, _ in metrics}
    for b in baselines:
        cells = []
        for key, _ in metrics:
            delta, p = rows_out[b][key]
            sign = "+" if delta > 0 else ""
            cell_d = "{}{:.3f}".format(sign, delta)
            if p is None:
                cell_p = "--"
            else:
                ph = adj[key][b]
                cell_p = "$<$0.001" if ph < 0.001 else "{:.3f}".format(ph)
            cells += [cell_d, cell_p]
        lines.append("{} & {} \\\\".format(POL_LABEL[b].replace("\\textbf", "").replace("\\emph", ""),
                                          " & ".join(cells)))
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    write(os.path.join(TABLES, "tab_stats.tex"), "\n".join(lines))
    return rows_out, adj


