def summary_json(data, floor_rows):
    out = {"scenarios": SCENARIOS, "policies": POLICIES, "main": {}, "floor": {},
           "trace": {}}
    for sc in SCENARIOS:
        out["main"][sc] = {}
        for pol in POLICIES:
            out["main"][sc][pol] = {
                key: {"mean": mean(data, sc, pol, key),
                      "std": std(data, sc, pol, key)}
                for key in METRICS
            }
    # Attack-scenario aggregates, used in the abstract and discussion.
    out["attack_mean"] = {}
    for pol in POLICIES:
        out["attack_mean"][pol] = {}
        for key in ("ivr_per_1k", "ivr_readwrite_per_1k", "ivr_actuate_per_1k",
                    "ivr_safety_per_1k", "unsafe_grant", "utility", "brier",
                    "switches_per_1k", "energy_mj", "p50_ms", "p99_ms",
                    "sram_kb", "flash_kb", "false_deny", "safety_denied"):
            xs = [mean(data, sc, pol, key) for sc in ATTACK]
            xs = [x for x in xs if not math.isnan(x)]
            out["attack_mean"][pol][key] = float(np.mean(xs)) if xs else float("nan")
    floor_json = os.path.join(RESULTS, "floor_sensitivity.json")
    if os.path.exists(floor_json):
        with open(floor_json, encoding="utf-8") as fh:
            fj = json.load(fh)
        for name, a in fj.get("floors", {}).items():
            out["floor"][name] = {
                "unsafe_grant_attack": a["unsafe_grant_attack"]["mean"],
                "utility_attack": a["utility_attack"]["mean"],
                "ivr_max": a["ivr_per_1k"]["mean"],
                "false_deny": a["false_deny"]["mean"],
                "energy_mj": a["energy_mj"]["mean"],
            }
    with open(os.path.join(RESULTS, "trace_priors.json"), encoding="utf-8") as fh:
        t = json.load(fh)
    out["trace"] = {
        "contrast": t["pooled"]["log_rate_contrast"]["point"],
        "ci95": t["pooled"]["log_rate_contrast"]["ci95"],
        "sim_contrast": t["simulator"]["log_contrast"],
    }
    write(os.path.join(RESULTS, "summary.json"), json.dumps(out, indent=2))


