def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def main_table(data, metric, caption, label, lower, d, bold=True):
    lines = [
        "% Generated by make_paper_assets.py — do not edit by hand; regenerate.",
        r"\begin{table*}[t]", r"\centering", r"\scriptsize",
        r"\setlength{\tabcolsep}{3.0pt}",
        r"\caption{" + caption + "}",
        r"\label{" + label + "}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{l" + "c" * (len(SCENARIOS) + 1) + "}",
        r"\toprule",
        "Policy & " + " & ".join(SCEN_LABEL[s] for s in SCENARIOS) + r" & Attack mean \\",
        r"\midrule",
    ]
    for pol in POLICIES:
        cells = []
