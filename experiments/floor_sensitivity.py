#!/usr/bin/env python3
"""Sensitivity of the results to the strength of the actuation floor (I1).

The invariant floor is the *minimum* posture that adaptation cannot cross. It is a
design parameter, not a theorem: a stronger floor lowers residual exposure to a
credential-holding attacker but costs energy and false denials. This script reruns the
full scenario matrix for four floors and writes the aggregate table used in the paper.

    python3 floor_sensitivity.py --seeds 10 --jobs 8

Output
    results/floor_sensitivity.csv      per (floor, seed, scenario, policy) rows
    results/floor_sensitivity.json     aggregated means/stds + metadata
    results/tab_floor_sensitivity.tex  booktabs table for the manuscript
"""

from __future__ import annotations

import argparse
import csv
import json
import os
from collections import defaultdict
from concurrent.futures import ProcessPoolExecutor

import numpy as np

import simulator as s

FLOORS = {
    # name: (actuation floor, safety floor), both as action-space index tuples
    # (auth, crypto, ids, rate, ttl)
    "mutual+header": {
        "actuate": (1, 1, 1, 0, 1),
        "safety": (1, 1, 2, 0, 1),
    },
    "attest+header": {
        "actuate": (2, 1, 1, 0, 1),
        "safety": (2, 1, 2, 0, 1),
    },
    "mutual+deep": {
        "actuate": (1, 1, 2, 0, 1),
        "safety": (1, 1, 2, 0, 1),
    },
    "attest+deep": {
        "actuate": (2, 1, 2, 0, 1),
        "safety": (2, 1, 2, 0, 1),
    },
}
HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "results")
SCENARIOS = s.SCENARIOS
POLICIES = s.POLICIES
DEFAULT_FLOOR = dict(s.STRUCT_FLOOR)


def _task(args):
    floor_name, seed, scenario, epochs = args
    s.STRUCT_FLOOR = {**DEFAULT_FLOOR, **FLOORS[floor_name]}
    return floor_name, s.run_one((seed, scenario, epochs))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--seeds", type=int, default=10)
    ap.add_argument("--epochs", type=int, default=2000)
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--out", default=os.path.join(RESULTS, "floor_sensitivity.csv"))
    args = ap.parse_args()

    tasks = [(name, seed, sc, args.epochs)
             for name in FLOORS for seed in range(1, args.seeds + 1) for sc in SCENARIOS]
    rows = []
    with ProcessPoolExecutor(max_workers=args.jobs) as ex:
        for floor_name, result in ex.map(_task, tasks):
            for r in result:
                r = dict(r)
                r["floor"] = floor_name
                rows.append(r)

    os.makedirs(RESULTS, exist_ok=True)
    fields = list(rows[0].keys())
    with open(args.out, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)

    # Aggregate over seeds. Energy is averaged over all scenarios; safety/utility are
    # also reported for the attack scenarios only, which is where the floor acts.
    agg = defaultdict(lambda: defaultdict(list))
    for r in rows:
        if r["policy"] != "full":
            continue
        for key in ("ivr_per_1k", "unsafe_grant", "false_deny", "utility",
                    "switches_per_1k", "energy_mj", "brier"):
            val = float(r[key])
            if val == val:  # skip nan
                agg[r["floor"]][key].append(val)
                if r["scenario"] != "none":
                    agg[r["floor"]][key + "_attack"].append(val)

    summary = {}
    for name in FLOORS:
        summary[name] = {}
        for key, vals in agg[name].items():
            summary[name][key] = {
                "mean": float(np.mean(vals)),
                "std": float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0,
                "n": len(vals),
            }
        summary[name]["actuate_floor"] = list(FLOORS[name]["actuate"])
        summary[name]["safety_floor"] = list(FLOORS[name]["safety"])

    with open(os.path.join(RESULTS, "floor_sensitivity.json"), "w", encoding="utf-8") as fh:
        json.dump({"seeds": args.seeds, "epochs": args.epochs,
                   "scenarios": SCENARIOS, "floors": summary}, fh, indent=2)

    lines = [
        "% Generated by floor_sensitivity.py — do not edit by hand; regenerate.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Sensitivity to the actuation floor (I1), Full policy, 10 seeds.",
        r"IVR, false denial and energy are means over all eight scenarios; malicious",
        r"grant and utility (marked $^{\ast}$) are means over the seven attack scenarios.",
        r"Every floor keeps invariant violations at zero; a stronger floor buys lower",
        r"residual exposure at a utility and energy cost.}",
        r"\label{tab:floor}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{lccccc}",
        r"\toprule",
        r"Actuation floor & IVR/1k & Malicious grant$^{\ast}$ & Utility$^{\ast}$ & False deny & Energy (mJ) \\",
        r"\midrule",
    ]
    labels = {
        "mutual+header": r"mutual auth + header IDS",
        "attest+header": r"attestation + header IDS",
        "mutual+deep": r"mutual auth + deep IDS",
        "attest+deep": r"attestation + deep IDS",
    }
    for name in FLOORS:
        a = summary[name]
        lines.append("{} & {:.2f} & {:.3f} & {:.3f} & {:.3f} & {:.3f} \\\\".format(
            labels[name],
            a["ivr_per_1k"]["mean"],
            a["unsafe_grant_attack"]["mean"],
            a["utility_attack"]["mean"],
            a["false_deny"]["mean"],
            a["energy_mj"]["mean"]))
    lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
    with open(os.path.join(RESULTS, "tab_floor_sensitivity.tex"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print("wrote", args.out)
    for name in FLOORS:
        a = summary[name]
        print("{:16s} IVR={:.2f} grant={:.3f} util={:.3f} fdeny={:.3f} energy={:.3f}".format(
            name, a["ivr_per_1k"]["mean"], a["unsafe_grant_attack"]["mean"],
            a["utility_attack"]["mean"], a["false_deny"]["mean"], a["energy_mj"]["mean"]))


if __name__ == "__main__":
    main()
